section('ALERTS REACH PEOPLE');
const got = [];
const hook = http.createServer((req, res) => { let b = ''; req.on('data', d => { b += d; }); req.on('end', () => { got.push(JSON.parse(b).text); res.end('ok'); }); });
await new Promise(res => hook.listen(0, res));
await setConfig('ALERT_WEBHOOK_URL', `http://localhost:${hook.address().port}/x`, { group: 'alerts' });
const a1 = await raiseAlert({ key: 'k1', severity: 'critical', title: 'Something broke', detail: 'details here' });
check('an alert is delivered to the chat address', got.length === 1 && /Something broke/.test(got[0]) && /CRITICAL/.test(got[0]) && a1.notified.includes('webhook'));
await raiseAlert({ key: 'k1', severity: 'critical', title: 'Something broke' });
check('the same problem is not repeated within the hour', got.length === 1 && (await SystemAlert.findOne({ key: 'k1' })).count === 2);
await resolveAlert('k1');
await raiseAlert({ key: 'k1', severity: 'critical', title: 'Something broke' });
check('a problem that comes back after being resolved is announced again', got.length === 2);
await SystemAlert.deleteMany({});


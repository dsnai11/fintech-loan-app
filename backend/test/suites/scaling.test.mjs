section('DOING MANY THINGS AT ONCE');
let running = 0, peak = 0;
const r = await mapLimit(Array.from({ length: 40 }, (_, i) => i), 5, async i => { running++; peak = Math.max(peak, running); await new Promise(res => setTimeout(res, 5)); running--; if (i === 7) throw new Error('one bad item'); return i; });
check('never more than 5 at the same time', peak <= 5 && peak > 1, `peak ${peak}`);
check('one failure is counted and the rest still finish', r.failed === 1 && r.results.filter(x => x !== undefined).length === 39);
let calls = 0;
const [c1, c2, c3] = await Promise.all([1, 2, 3].map(() => cached('k', 1000, async () => { calls++; await new Promise(res => setTimeout(res, 20)); return 'v'; })));
check('three staff opening the same page cost one calculation', calls === 1 && c1 === 'v' && c3 === 'v');

section('A JOB RUNS ONCE EVEN WITH SEVERAL SERVERS');
let ran = 0;
const slow = () => runLocked('t-job', 5000, async () => { ran++; await new Promise(res => setTimeout(res, 150)); return 'done'; });
const both = await Promise.all([slow(), slow(), slow()]);
check('three servers start it at once: it runs one time', ran === 1 && both.filter(x => x.ran).length === 1 && both.filter(x => x.skipped).length === 2, JSON.stringify(both));
const again = await slow();
check('afterwards it can run again', again.ran === true && ran === 2);
let told = null;
const failed = await runLocked('t-fail', 5000, async () => { throw new Error('boom'); }, { onFail: async (name, e) => { told = `${name}:${e.message}`; } });
const lock = await JobLock.findOne({ name: 't-fail' });
check('a failing job is recorded and reported, and does not crash', failed.error === 'boom' && told === 't-fail:boom' && lock.failures === 1 && lock.lastError === 'boom');
// A run longer than its lock time keeps the lock, so a second server cannot start the same job
let longRuns = 0;
const longJob = () => runLocked('t-long', 1500, async () => { longRuns++; await new Promise(res => setTimeout(res, 2600)); });
const l1 = longJob();
await new Promise(res => setTimeout(res, 2000));
const l2 = await longJob();
await l1;
check('a job that outlasts its lock time still cannot be started twice', longRuns === 1 && l2.skipped === true, `${longRuns} ${JSON.stringify(l2)}`);
await JobLock.updateOne({ name: 't-job' }, { holder: 'another-server', until: new Date(Date.now() + 60000) });
check('while another server holds the lock, this one stays out', (await slow()).skipped === true);
await JobLock.updateOne({ name: 't-job' }, { until: new Date(Date.now() - 1000) });
check('a lock left by a dead server expires on its own', (await slow()).ran === true);

section('SEVERAL SERVERS SHARE THE REQUEST LIMIT AND THE SETTINGS');
const A = await startServer(DB, { RATE_LIMIT_STORE: 'shared', API_RATE_LIMIT: '6', CONFIG_REFRESH_SECONDS: '1' });
const B = await startServer(DB, { RATE_LIMIT_STORE: 'shared', API_RATE_LIMIT: '6', CONFIG_REFRESH_SECONDS: '1' });
const ca = client(A.base), cb = client(B.base);
// Starting a server polls /health, and those requests count against the shared limit: start from zero
await (await import('mongoose')).default.connection.collection('ratelimits').deleteMany({});
const codes = [];
for (let i = 0; i < 4; i++) codes.push((await ca('GET', '/pricing')).s);
for (let i = 0; i < 4; i++) codes.push((await cb('GET', '/pricing')).s);
check('6 requests allowed across both servers, then refused (429)', codes.filter(c => c === 200).length === 6 && codes.filter(c => c === 429).length === 2, codes.join());
A.stop(); B.stop();

const A2 = await startServer(DB, { CONFIG_REFRESH_SECONDS: '1' });
const B2 = await startServer(DB, { CONFIG_REFRESH_SECONDS: '1' });
const cb2 = client(B2.base);
check('before the change, server B shows no banner', (await cb2('GET', '/app-settings')).d.banner?.enabled === false);
await Config.findOneAndUpdate({ key: 'APP_SETTINGS' }, { key: 'APP_SETTINGS', value: JSON.stringify({ banner: { enabled: true, level: 'info', text: 'Hello from server A' } }), group: 'app' }, { upsert: true });
await new Promise(res => setTimeout(res, 2500));
check('a setting changed elsewhere reaches server B within seconds', (await cb2('GET', '/app-settings')).d.banner?.text === 'Hello from server A');
A2.stop(); B2.stop();

